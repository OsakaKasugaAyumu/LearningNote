/**
 *  CAN :
 *      - CAN控制器通过两根线上的电位差来判断总线电平
 *      - 总线电平分为显性电平和隐性电平
 *          - 显性电平(逻辑0) : CANH和CANL差大2V
 *          - 隐性电平(逻辑1) : CANH和CANL差接近0V
 * 
 *          PS:线与核心, 只要有一个节点发出显性电平, 那么整条总线就是显性的
 * 
 * 
 *  CAN Transceiver(CAN收发器) :
 *      典型的比如TJA1050: 
 *          8 Pins
 *          - TXD : reads in data from CAN Controller to the bus line drivers
 *          - RXD : reads out data from CAN bus line to the CAN Controller
 *          - S : select input for high-speed mode or silent mode
 *          - CANH/CANL
 *          - Vcc/GND/Vref    
 * 
 *      CAN Controller  --- 3.3V逻辑电平 ---> CAN Transceiver --- CANH/CANL ---> CAN Bus
 * 
 *  CAN总线的特点 : 
 *      - 多主 + CSMA/CA实现非破坏性仲裁, ID优先级最高获得发送权, 其他节点失去仲裁权之后, 立刻转为接收, 效率极高
 *      - ID不是目标地址, 是优先级标签, 面向广播的通信
 *      - 没有MAC/IP之类的节点地址, 只有ID(消息内容的优先级/类型), 增加新节点, 只需要配好新节点的过滤规则即可
 *      - 全网节点统一通信速度, 错误帧惩罚, 只要有一个节点波特率设置错误, 就不断的输出错误帧
 *  
 * 
 *  CAN总线的三大错误状态 : 
 *      - 主动错误状态 (Error Active)
 *      - 被动错误状态 (Error Passive)
 *      - 总线关闭状态 (Bus Off)
 * 
 *      核心机制 : 
 *          - TEC : (发送错误寄存器) 发送失败增加, 发送成功减少
 *          - REC : (接收错误寄存器) 接收失败增减, 接收成功减少
 * 
 *      上电/复位(Error Active)  --- TEC > 127 || REC > 127 --> (Error Passive) --- TEC > 255 --> (Bus Off)节点隔离
 * 
 *      (Bus Off) --- 在总线上检测到128次连续的11个隐性位 --> (Error Active)
 * 
 * 
 *      PS: 状态转换阈值 127(主动变被动) 256(被动变关闭) 128次11位隐性位(关闭变主动)
 *          Error Active和Error Passive的区别 :
 *              Error Active发 "显性" 错误帧(逻辑0)
 *              Error Passive发 "隐性" 错误帧(逻辑1) 
 *      
 *          CAN通过技术器自动识别状态, 一旦是Bus Off, 就强制下线, 保全整体网络
 * 
 * 
 *  CAN总线协议 :
 *      Layer 1 :
 *          位编码格式 : 位填充机制, 发送端连续5个相同的极性位之后强行插入一个相反位, 接收端连续检测到6个相同的位则报错
 * 
 *      Layer 2 : 
 *          消息帧化 : 数据帧  遥控帧  错误帧  过载帧四种
 *          数据冲突时仲裁 : 根据ID优先级, 显性电平(0)压制隐性电平(1)
 *          错误 : CRC错误, 填充位错误, 位错误, ACK错误, 格式错误
 *          应答方式 : ACK  NACK
 *          通信方式 : 半双工(CANH/CANL是一对差分线)
 * 
 *      Layer 2 : 
 *          过滤 : 验收滤波器, 判断是否接收该帧
 *          过载 : 接收方来不及处理, 发送一个过载帧给发送方等一下
 *          重传 : 错误恢复功能
 * 
 *      Layer 4 : 
 *          再发送机制 : 无限次重发, 直到成功
 * 
 *      
 * 
 *  CAN分为两种 : 高速CAN和低速CAN
 * 
 *          高速CAN(ISO11898) : 125kbps - 1Mbps, 最长40m, 最大节点数30个
 *          低速CAN(ISO11519) : 10kbps - 125kbps, 最长1km, 最大节点数20个
 * 
 *          高速CAN : 闭环总线(两端接一个120Ω电阻)
 *          低速CAN : 开环总线(各节点独立接2.2KΩ电阻)
 * 
 *          高速CAN : 隐性(CAN_H和CAN_L都在2.5V, 电位差0V) 显性(CAN_H在3.5V, CAN_L在1.5V, 电位差2V)
 *          低速CAN : 隐性(CAN_H在1.75V, CAN_L在3.25V) 显性(CAN_H拉高到4.0V, CAN_L拉低到1.0V) 
 *      
 *      PS: 线与的原理 : 只要有一个节点发出显性(0), 整个总线就是显性, 因为显性的电位差大, 压制隐性
 *                       只有所有的节点都是隐性, 总线才是隐性
 * 
 *  
 *  
 * 
*/


/**
 * 
 * 汽车选择CAN总线: CAN的非破坏性逐位仲裁（ID优先级）决定了：只要优先级高（比如刹车信号），哪怕总线拥堵，也能零延迟立刻抢占总线。这种确定性是普通网络不具备的。
 *  
 *      多主, 广播, 硬件过滤, 半双工
 *      - CAN网络去中心化, 没有主从之分, 所有的节点(ECU)地位平等
 *      - CAN提供了本地过滤(验收滤波器), 自动过滤掉无关的报文   
 * 
 *                                                                           --120Ω--
 *                                                                           |      |
 *     |               | ---- CAN_TX ---->|                 | <--- CAN_H --->|      |
 *     | CAN Controller|                  | CAN Transceiver |                |      |
 *     |               | <---- CAN_RX ----|                 | <--- CAN_L ----|----->|
 *                                                                           |      |
 *                                                                           |      |
 *                                                                           --120Ω--
 * 
 *      Layer2(数据链路层)对应 CAN Controller
 *      Layer1(物理层)对应 CAN Transceiver
 * 
 * 
 *  CAN通信的五种帧格式 :
 *      - 数据帧 : 用于发送单元向接收单元传送数据, 唯一需要主动打包和发送的帧
 *      - 遥控帧 : 用于接受单元向具有相同ID的发送单元请求数据的帧, 主动索取机制
 *      - 错误帧 : 用于当检测出错误的时候向其他单元通知错误的帧, CAN鲁棒性的核心, 当任一节点检测到位错误, CRC错误或填充错误, 硬件自动打断当前通信, 发送错误帧(主动错误6个显性位, 被动错误6个隐性位)
 *      - 过载帧 : 用于接受单元通知其尚未做好接收准备的帧, 流控机制
 *      - 帧间隔 : 用于数据帧及遥控帧与前面的帧分离开, 帧之间的强制休息时间(3个隐性电平)
 * 
*/

/**
 *  常用的三种帧结构 : 
 *      - 遥控帧
 *          
 *      - 标准帧
 * 
 *      - 扩展帧
 * 
 * 
 * 
 *  帧结构字段 : 
 *      SOF [1 bit]     : 帧起始, 总线空闲后第一个显性电平, 用于所有节点的硬同步
 *      ID  [11 bit]    : 帧唯一标识, 数值越小, 优先级越高
 *      RTR [1 bit]     : 远程发送请求位, 0(显性)数据帧,  1(隐性)遥控帧
 *      SRR [1 bit]     : 替代RTR, 规定为隐性1, 核心作用是标准帧和扩展帧同时发送时, 保证仲裁机制完美兼容[标准帧(RTR为0)压制扩展帧(SRR为1)]
 *      IDE [1 bit]     : 标识符扩展位, 0标准帧(11 bit ID)  1扩展帧(29 bit ID)
 *      R   [1 bit]     : 保留位
 * 
 *      DLC [4 bit]     : 数据位有效字节数, 经典CAN的数据长度范围(0b0000 - 0b1000)最大8bytes, CAN FD进行了扩展(0b1001 - 0b1111)最大可以表示64 bytes
 * 
 *      CRC [15 bit]    : 循环冗余校验, 发送方根据前面数据算出一个15 bit的值, 接收方接收到之后, 再计算一遍, 如果不一致, 检测出CRC错误, 触发错误帧, TEC计数增加
 *      DEL [1 bit]     : 界定符, 固定隐性1, 隔开CRC段和控制段
 *      ACK [1 bit]     : 应答位, 发送方发隐性, 只要有一个节点正确接受了, 就在这个位发显性, 如果接收方再ACK槽检测到隐性, 说明没人收到, 直接触发ACK错误
 * 
 *      EOF [7 bit]     : 帧结束, 固定7个连续的隐性位, 如果出现了显性, 则格式错误帧
 *      ITM [3 bit]     : 帧间隔, 固定3个连续的隐性位, 强制!!!
 * 
 *      
 * 
 *      RTR :
 *          - 0 标准帧
 *          - 1 遥控帧
 * 
 *      IDE : 
 *          - 0 标准帧 (核心, 标准帧压制扩展帧)
 *          - 1 扩展帧
 * 
 *      SRR : 
 *          - 1 扩展帧独有, 和标准帧进行仲裁机制的时候, 被标准帧压制的位
 * 
 *      如果一个帧没有错误, 以下五个信号固定
 *          - SOF, ACK显性
 *          - DEL, EOF, ITM隐性
 * 
 * 
 *      标准格式 :
 *          起始段   仲裁段(SOF后一bit, DLC前一位)                       控制段             数据段                CRC段             ACK段               帧结束段      
 *          SOF      ID + RTR                                           IDE + r0 + DLC     data bit(0 - 64)      CRC + DEL         ACK + DEL           EOF + ITM
 * 
 *      扩展格式 : 
 *          起始段  仲裁段                                              控制段
 *          SOF     ID(11 bit) + SRR + IDE + ID(18 bit) + RTR           r1 + r0 + DLC       ...
 * 
 * 
 *      
 * 终极优先级排序（假设ID完全相同）
    把前面的结论全部串联起来，从高到低依次是：
    标准数据帧 （最高：RTR=0 直接秒杀其他）
    标准遥控帧 （次高：RTR=1平局，IDE=0 胜出）
    扩展数据帧 （RTR=0 vs 扩展遥控帧的RTR=1，胜出）
    扩展遥控帧 （最低）
 * 
 * 
 *  错误帧 : 
 *      物理层 
 *      - Error Active : 6 bit 显性 + 8 bit 隐性界定符
 *      - Error Passive : 6 bit 隐性 + 8 bit 隐性界定符
 *           
 *  过载帧 :
 *      6 bit 显性 + 8 bit 隐性界定符
 * 
 *  帧间隔 :
 *      - Error Active : 3 bit 隐性
 *      - Error Passive : 3 bit 隐性 + 8 bit 隐性延时
 * 
*/



/**
 *  CAN总线的控制段 (标准帧和扩展帧都是6 bit) 
 *      - 标准帧 : IDE + r0 + DLC
 *      - 扩展帧 : r1 + r0 + DLC
 * 
 * 
 *  后续四段(数据段, CRC段, ACK段, 帧结束段)标准帧和扩展帧都一样 :
 *      - 数据段 : MSB  0-64 bit
 *      - CRC段 : CRC(15 bit) + CRC界定符(隐性R), 从SOF到数据段, 全部参与CRC校验
 *      - ACK段 : ACK槽 + ACK界定符(隐性R)
 *                  - 发送方发送隐性
 *                  - 接收方正确接收(无填充错误, 格式错误, CRC错误), 并且不处于总线关闭态, 必须再ACK槽中回复显性
 *      - 结束段 : 连续7个隐性位, 只要出现一个显性, 格式错误
 * 
 * 
 * 
 *  CAN节点的核心机制 : 发送 + 回读机制
 *      - 这是非破坏性仲裁的前提
 * 
 * 
 *      发送 + 回读机制, 如果发送出去的电平和回读电平不一样, 分四种情况
 *          - 仲裁段 : 发送出去1, 回读到0, 退出总线竞争
 *          - 控制段, 数据段, CRC段 : 如果发送和回读不一样, 产生位错误, 发送错误帧
 *          - ACK段 : ACK Slot期间, 发送1, 回读0是正确且必须的
 *          - 被动错误标志传输期间 : 发送错误帧 6个隐性1, 如果其他正常节点发送显性, 回读不同, 但不能报错
 * 
 * 
 * 
 *  位填充区域(bit) : [SOF, CRC界定符)  不包含CRC界定符
 *  位填充机制 : 在位填充区域, 不会出现连续6 bit相同的电平
 * 
 * 
 *  五大错误分类 :
 *      - 发送方专属 : 
 *          - ACK错误 : 发送方在ACK Slot中没有读到显性电平
 * 
 *      - 接收方专属 :
 *          - CRC错误 : 接收方接收到数据计算的CRC结果和发送过来的不一样
 *          - 格式错误 : 比如EOF连续7个隐性电平, 却出现了显性电平
 * 
 *      - 双方 : 
 *          - 位填充错误, 物理层连续监测到了6个连续相同的电平
 *          - 位发送错误 : 发送方在控制段, 数据段, CRC段发送和回读的电平不一样
 * 
 * 
 * 
 *      PS:CRC错误必须忍到ACK界定符后才发错误帧。 其他四种错误, 一出错立刻发错误帧
*/

